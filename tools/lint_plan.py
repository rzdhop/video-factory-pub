#!/usr/bin/env python3
"""Static check of episodes/<id>/{plan.json, script.md} BEFORE any voice credit is spent.

Usage: lint_plan.py <episode_dir>
Prints `WARN  ...` / `ERROR ...` lines and a summary; exit 1 when there is at least one ERROR.
Checks the format, the script/plan structure, block sizes and accents, every chapter/word reference
(direction, retime, sfx_events, host_set.reveal, media), the enums the engine and the tools accept,
the sound-effect budget, the vulgarity policy of the format, media files, the hook-first `opening` block
(WARN when a `layout: 2` plan has none) and the series block.
Scenes: only the names of the generated src/layers/scenes/index.ts (tools/gen_scenes.py) are registered;
an unknown scene or a stale index is a WARN before episode.json exists and an ERROR after (render is near).
Every required b("word") literal of a scene component must occur in a block of the chapter that uses the
scene (skipped for fallbacks such as Math.min(b("a"), b("b")) and for a scene shared with another episode).
"""
import json, pathlib, re, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import formats  # noqa: E402
import lang as langs  # noqa: E402
import gen_scenes  # noqa: E402

ROOT = formats.ROOT

# enums accepted by tools/direct.py, tools/build_sfx.py and src/types.ts
EMOTIONS = {"idle", "happy", "wink", "curious", "confused", "amazed", "panic", "deadpan", "smug"}
SHOTS = {"bust", "close", "peek"}
GESTURES = {"wave", "point", "shrug", "balance", "none"}
TRANSITIONS = {"whip-left", "whip-right", "whip-up", "zoom", "flash"}
SFX_KINDS = {"plop", "flush", "thud", "pop", "ding", "boom"}
MUSIC_SECTIONS = {"intro", "full", "half", "outro", "none"}


def sfx_kinds(plan):
    """Kinds an sfx event may name: the six synthesized ones, or, with "sound_kit", the roles of the kit plus
    every id of the sound library (same rule as tools/build_sfx.py)."""
    kit = plan.get("sound_kit")
    if not kit:
        return SFX_KINDS
    kit_path = ROOT / "sounds" / "kits" / f"{kit}.json"
    lib_path = ROOT / "sounds" / "library.json"
    kinds = set()
    if kit_path.exists():
        kinds |= set(json.loads(kit_path.read_text()).get("roles", {}))
    if lib_path.exists():
        kinds |= set(json.loads(lib_path.read_text()).get("sounds", {}))
    return kinds
MEDIA_FIT = {"cover", "contain"}
MEDIA_MOTION = {"push", "pull", "pan-left", "pan-right", "none"}
MEDIA_EXT = {"image": {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif", ".svg", ".bmp"},
             "video": {".mp4", ".mov", ".webm", ".m4v", ".mkv"}}
BUILTIN_SCENES = {"media"}
BIG_SFX_GAIN = 0.4       # same threshold as build_sfx.py (music stop) and direct.py (reaction close-up)
WORDS_PER_SECOND = 3.2   # measured on a tightened voice take (179 words in 55 s); set per language in lint()
OPENING_HOST = {"bust", "hidden"}
OPENING_MAX_S = 4        # same cap as src/layers/OpeningCard.tsx
OPENING_LINE_CHARS = 18  # beyond, a title line is set under about 115 px
# greeting and swear word lists, counted-word rule and speech rate follow the language of the episode
# (tools/lang.py, docs/LANGUAGE.md); French until lint() has read plan.json
LANG = langs.DEFAULT
GREETING = langs.spec(LANG)["greeting"]
FOLLOW = re.compile(r"abonn|suis[- ]moi|\bfollow|subscrib", re.I)  # follow call, French and English
SWEARS = langs.spec(LANG)["swears"]

errors, warns = [], []
err, warn = errors.append, warns.append


def counted_words(text):
    """Same rule as tools/validate_episode.py: articles do not count (tools/lang.py, per language)."""
    return langs.counted_words(text, LANG)


def spoken_words(text):
    return len([x for x in text.replace("*", "").split() if re.search(r"\w", x)])


def known_characters():
    """Character ids the engine can draw: the keys of `HOSTS` in src/layers/Character.tsx, the rig-less mascot
    "volt" and "none" (hostless layout). Empty set when the file cannot be read (the check is then skipped)."""
    path = ROOT / "src" / "layers" / "Character.tsx"
    src = path.read_text(encoding="utf-8") if path.is_file() else ""
    m = re.search(r"\bHOSTS\b[^=]*=\s*\{", src)
    if not m:
        return set()
    _body, flat = gen_scenes.literal(src, m.end())
    names = {k.group(1) or k.group(2) or k.group(3) for k in gen_scenes.KEY.finditer(flat)}
    return names | {"volt", "none"}


def registered_scenes():
    """(names really registered for the render, scan of the scene files, reasons why the index is stale).
    Only what src/layers/scenes/index.ts (generated by tools/gen_scenes.py) lists is rendered: a scene
    file that is not in the index yet does not count."""
    names = set(BUILTIN_SCENES)
    try:
        found = gen_scenes.scan()
        stale = gen_scenes.stale_reasons(found)
    except OSError as exc:
        return names, [], [f"scene files not readable ({exc})"]
    if gen_scenes.INDEX.is_file():
        names |= gen_scenes.index_names(gen_scenes.INDEX.read_text(encoding="utf-8"))
    return names, found, stale


def scenes_of_other_episodes(ep_dir):
    """Scene names used by the plan.json of the other episodes of the same episodes/ folder."""
    names = set()
    me = ep_dir.resolve()
    for plan_path in me.parent.glob("*/plan.json"):
        if plan_path.parent == me:
            continue
        try:
            other = json.loads(plan_path.read_text(encoding="utf-8"))
            names |= {c.get("scene") for c in other.get("chapters", []) if isinstance(c, dict)}
        except (OSError, ValueError, AttributeError):
            continue
    return names


def parse_script(text):
    """Same parsing as tools/build_episode.py: `### <Title> — HUD: <label>`, then the first text line."""
    out = []
    for sec in re.split(r"^### ", text, flags=re.M)[1:]:
        head, _, body = sec.partition("\n")
        para = next((l.strip() for l in body.splitlines() if l.strip() and not l.startswith("#")), "")
        out.append((head.strip(), para))
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ep_dir = pathlib.Path(sys.argv[1])
    plan_path, script_path = ep_dir / "plan.json", ep_dir / "script.md"

    # ---------- plan.json ----------
    try:
        plan = json.loads(plan_path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return finish(ep_dir, [f"{plan_path} not found"])
    except json.JSONDecodeError as exc:
        return finish(ep_dir, [f"plan.json does not parse: {exc}"])
    if not isinstance(plan, dict) or not isinstance(plan.get("chapters"), list) or not plan["chapters"]:
        return finish(ep_dir, ["plan.json has no `chapters` list"])
    for key in ("id", "title", "preset", "character", "fps", "voice"):
        if key not in plan:
            err(f"plan.json: missing `{key}` (tools/build_episode.py needs it)")
    if "id" in plan and plan["id"] != ep_dir.resolve().name:
        warn(f"plan.json id '{plan['id']}' differs from the folder name '{ep_dir.resolve().name}'")
    try:  # look of the episode / series / format (tools/looks.py)
        import looks as _looks
        _lk = _looks.resolve(plan)
        for _e in (_looks.validate(_lk) if _lk else []):
            err(f"look: {_e}")
    except SystemExit as _x:
        err(f"look: {_x}")
    if isinstance(plan.get("preset"), str) and not (ROOT / "presets" / f"{plan['preset']}.json").is_file():
        err(f"preset '{plan['preset']}' has no presets/{plan['preset']}.json")

    # ---------- format ----------
    fmt = None
    fid = plan.get("format")
    if fid is None:
        warn(f"plan.json has no `format`: '{formats.DEFAULT}' assumed")
        fid = formats.DEFAULT
    try:
        fmt = formats.load(fid)
        bad = formats.validate(fmt)
        if bad:
            err(f"format '{fid}' is invalid ({len(bad)} problem(s), run tools/formats.py)")
            fmt = None
    except (ValueError, json.JSONDecodeError) as exc:
        err(f"format: {exc}")
    if fmt and fmt["production"] == "ai":
        warn(f"format '{fid}' is produced with an outside AI generation service, not with this pipeline")
    hostless = plan.get("character") == "none"
    _chars = known_characters()
    if _chars and isinstance(plan.get("character"), str) and plan["character"] not in _chars:
        err(f"character '{plan['character']}' is not drawn by the engine (known: {', '.join(sorted(_chars))}): "
            "the host would be missing. Create it from src/layers/characters/Host.tsx and register it in "
            "src/layers/Character.tsx (HOSTS), or use \"host\" / \"none\"")

    # ---------- language (docs/LANGUAGE.md) ----------
    global LANG, GREETING, SWEARS, WORDS_PER_SECOND
    if plan.get("lang") is not None and plan.get("lang") not in langs.LANGS:
        err(f"lang: unknown language {plan.get('lang')!r} (known: {', '.join(langs.LANGS)})")
        LANG = langs.DEFAULT
    else:
        LANG = langs.resolve({k: v for k, v in plan.items() if k != "lang" or v})[0]
    L = langs.spec(LANG)
    GREETING, SWEARS, WORDS_PER_SECOND = L["greeting"], L["swears"], L["words_per_second"]
    _series = plan.get("series")
    _slug = _series.get("slug") if isinstance(_series, dict) else None
    _saga = langs.series_lang(_slug) if _slug else None
    if _saga and _saga != LANG:
        err(f"lang: this part is in '{LANG}' but the saga '{_slug}' is in '{_saga}' (a saga speaks one language)")
    _espeak = (plan.get("voice") or {}).get("voice")
    if plan.get("lang") and _espeak in {x["espeak"] for x in langs.LANGS.values()} and _espeak != L["espeak"]:
        warn(f"voice.voice is '{_espeak}' but the episode is in '{LANG}': tools/build_episode.py uses '{L['espeak']}' "
             "for the reference timing")

    # ---------- chapters ----------
    chapters = plan["chapters"]
    keys = []
    scenes, scene_files, stale = registered_scenes()
    # once episode.json exists the render is near: a scene that is not registered would render blank
    built = (ep_dir / "episode.json").is_file()
    late = err if built else warn
    for reason in stale:
        late(f"scene registry: {reason}: run tools/gen_scenes.py")
    unregistered = {s: f["file"].name for f in scene_files for s in f["scenes"]} if stale else {}
    for i, c in enumerate(chapters):
        if not isinstance(c, dict) or not isinstance(c.get("key"), str) or not c.get("key"):
            err(f"chapter {i}: missing `key`")
            keys.append(None)
            continue
        k = c["key"]
        if k in keys:
            err(f"chapter key '{k}' is used twice")
        keys.append(k)
        if not c.get("label"):
            warn(f"chapter {k}: no HUD `label`")
        if not isinstance(c.get("hud", {}), dict):
            err(f"chapter {k}: `hud` must be an object")
        scene = c.get("scene")
        if not scene:
            err(f"chapter {k}: missing `scene`")
        elif scene not in scenes:
            if scene in unregistered:
                late(f"chapter {k}: scene '{scene}' exists in {unregistered[scene]} but is not in the generated "
                     "index: run tools/gen_scenes.py")
            elif built:
                err(f"chapter {k}: scene '{scene}' is not registered (no *_SCENES export of src/layers/scenes "
                    "has it): it would render blank")
            else:
                warn(f"chapter {k}: scene '{scene}' not built yet (not registered in src/layers)")
        if "transition" in c and c["transition"] not in TRANSITIONS:
            err(f"chapter {k}: unknown transition '{c['transition']}' (allowed: {', '.join(sorted(TRANSITIONS))})")
    key_set = {k for k in keys if k}

    # ---------- script.md ----------
    blocks = {}  # chapter key -> list of block texts without the accent marks
    if not script_path.is_file():
        err("script.md not found")
        sections = []
    else:
        sections = parse_script(script_path.read_text(encoding="utf-8"))
        _text = script_path.read_text(encoding="utf-8")
        if not any(v["fact_heading"] in _text for v in langs.LANGS.values()):
            warn(f"script.md has no `{L['fact_heading']}` section")
        # narration written in the other language than the one declared: wrong voice timing, wrong word lists
        _guess, _hits = langs.looks_like(" ".join(para for _h, para in sections if not para.startswith("<!--")))
        if _guess and _guess != LANG:
            err(f"lang: the narration reads as '{_guess}' ({_hits}) but the episode is declared '{LANG}': set `lang` in "
                "plan.json (and rebuild the reference timing) or rewrite the script")
    if script_path.is_file() and len(sections) != len(chapters):
        err(f"script.md has {len(sections)} `### ` sections, plan.json has {len(chapters)} chapters")
    total_words = 0
    for (head, para), key in zip(sections, keys):
        if key is None:
            continue
        name = f"chapter {key}"
        if not para or para.startswith("<!--") or "TODO" in para or para.startswith(("-", ">")):
            err(f"{name}: section '{head}' is not written yet")
            blocks[key] = []
            continue
        m = re.search(r"HUD\s*:\s*(.+)$", head)
        label = next((c.get("label") for c in chapters if isinstance(c, dict) and c.get("key") == key), None)
        if m and label and m.group(1).strip() != str(label).strip():
            warn(f"{name}: HUD label differs between script.md ('{m.group(1).strip()}') and plan.json ('{label}')")
        raw = [b.strip() for b in para.split("|") if b.strip()]
        blocks[key] = [b.replace("*", "") for b in raw]
        total_words += sum(spoken_words(b) for b in raw)
        for b in raw:
            clean = b.replace("*", "")
            n = counted_words(clean)
            if b.count("*") % 2:
                err(f"{name}: block '{b}' has an unclosed *accent*")
            elif len(re.findall(r"\*[^*]+\*", b)) > 1:
                err(f"{name}: block '{b}' has more than one *accent*")
            if not re.search(r"\w", clean):
                err(f"{name}: block '{b}' has no word")
            elif n > 4:
                err(f"{name}: block '{clean}' has {n} counted words (max 4)")
            elif n == 0:
                warn(f"{name}: block '{clean}' has only 1-2 letter words")
            if fmt and fmt["tone"]["vulgarity"] == "none":
                hit = SWEARS.search(clean)
                if hit:
                    warn(f"{name}: '{hit.group(0)}' in block '{clean}' (format '{fid}' has vulgarity none)")

    # ---------- b("word") beats of the scene components ----------
    # A scene reveals an element with b("word"): the time of the first block of ITS chapter containing the
    # word. A word that is in no block of the chapter never fires, so the element never appears.
    beats = {s: (f["file"].name, f["beats"][s]) for f in scene_files for s in f["beats"]}
    users = {}
    for c in chapters:
        if isinstance(c, dict) and c.get("key") in blocks and c.get("scene") in beats:
            users.setdefault(c["scene"], []).append(c["key"])
    shared = scenes_of_other_episodes(ep_dir) if users else set()
    for scene, chaps in users.items():
        if any(not blocks[k] for k in chaps):
            continue  # a chapter of this scene is not written yet
        if scene in shared:
            continue  # the same drawing serves another script: its words cannot be told apart
        fname, literals = beats[scene]
        where = "chapter " + chaps[0] if len(chaps) == 1 else "chapters " + ", ".join(chaps)
        for lit in literals:
            w = lit.lower()
            if any(w in b.lower() for k in chaps for b in blocks[k]):
                continue
            if any(w in " ".join(blocks[k]).lower() for k in chaps):
                warn(f"scene '{scene}' ({fname}): b(\"{lit}\") spans two blocks of {where}: element never appears "
                     "(a beat matches inside one block)")
            else:
                warn(f"scene '{scene}' ({fname}): b(\"{lit}\") is not in the script of {where}: element never appears")

    # ---------- format ranges ----------
    est = total_words / WORDS_PER_SECOND
    if fmt:
        lo, hi = fmt["chapters"]["min"], fmt["chapters"]["max"]
        if not lo <= len(chapters) <= hi:
            warn(f"{len(chapters)} chapters, format '{fid}' expects {lo}-{hi}")
        lo, hi = fmt["words"]["min"], fmt["words"]["max"]
        if sections and not lo <= total_words <= hi:
            warn(f"{total_words} words (about {est:.0f} s), format '{fid}' expects {lo}-{hi}")
        # docs/RETENTION.md rule 3: for new episodes the format's maximum length is a hard limit
        if sections and plan.get("layout") == 2 and est > fmt["duration_s"]["max"] * 1.08:
            err(f"about {est:.0f} s of speech, over the {fmt['duration_s']['max']} s limit of '{fid}': cut, or split into a series")

    # ---------- references to a word of a chapter ----------
    def ref(entry, label, need_word=True):
        """Check {"chapter", "word"}: ERROR when the chapter or the word does not exist. True when usable."""
        if not isinstance(entry, dict):
            err(f"{label}: not an object")
            return False
        chap, word = entry.get("chapter"), entry.get("word")
        if chap not in key_set:
            err(f"{label}: unknown chapter '{chap}'")
            return False
        if not isinstance(word, str) or not word.strip():
            if need_word:
                err(f"{label}: missing `word`")
            return False
        if chap not in blocks:  # no script for this chapter: already reported
            return False
        w = word.lower()
        if any(w in b.lower() for b in blocks[chap]):
            return True
        if w in " ".join(blocks[chap]).lower():
            warn(f"{label}: '{word}' spans two blocks of chapter '{chap}' (the tools match inside one block: entry ignored)")
        else:
            err(f"{label}: word '{word}' does not occur in chapter '{chap}'")
        return False

    def enum(entry, key, allowed, label):
        if isinstance(entry, dict) and key in entry and entry[key] not in allowed:
            err(f"{label}: unknown {key} '{entry[key]}' (allowed: {', '.join(sorted(allowed))})")

    def number(entry, key, label):
        if isinstance(entry, dict) and key in entry and (isinstance(entry[key], bool) or not isinstance(entry[key], (int, float))):
            err(f"{label}: `{key}` must be a number")

    def entries(value, label):
        if value is None:
            return []
        if not isinstance(value, list):
            err(f"`{label}` must be a list")
            return []
        return value

    direction = entries(plan.get("direction"), "direction")
    if direction and hostless:
        warn(f"`direction` has {len(direction)} entries but character is \"none\": ignored by the hostless layout")
    for i, d in enumerate(direction):
        label = f"direction[{i}]" + (f" ({d.get('chapter')}/{d.get('word')})" if isinstance(d, dict) else "")
        ref(d, label)
        enum(d, "emotion", EMOTIONS, label)
        enum(d, "shot", SHOTS, label)
        enum(d, "gesture", GESTURES, label)

    retime = plan.get("retime") or {}
    if not isinstance(retime, dict):
        err("`retime` must be an object")
        retime = {}
    for i, p in enumerate(entries(retime.get("pauses"), "retime.pauses")):
        label = f"retime.pauses[{i}]" + (f" ({p.get('chapter')}/{p.get('word')})" if isinstance(p, dict) else "")
        ref(p, label)
        number(p, "add", label)
    if retime.get("intro_after"):
        n_intro = int(retime.get("intro_blocks", 2))
        flat = [b for k in keys if k in blocks for b in blocks[k]]
        if flat and not any(str(retime["intro_after"]).lower() in b.lower() for b in flat[n_intro:]):
            err(f"retime.intro_after: no block after the {n_intro} intro blocks contains '{retime['intro_after']}'")

    big = 0
    for i, e in enumerate(entries(plan.get("sfx_events"), "sfx_events")):
        label = f"sfx_events[{i}]" + (f" ({e.get('chapter')}/{e.get('word')})" if isinstance(e, dict) else "")
        ref(e, label)
        if isinstance(e, dict):
            if "kind" not in e:
                err(f"{label}: missing `kind`")
            enum(e, "kind", sfx_kinds(plan), label)
            number(e, "gain", label)
            number(e, "offset", label)
            g = e.get("gain", 0.25)
            big += isinstance(g, (int, float)) and g >= BIG_SFX_GAIN

    host_set = plan.get("host_set")
    if host_set is not None and not isinstance(host_set, dict):
        err("`host_set` must be an object")
    elif host_set:
        if hostless:
            warn("`host_set` is set but character is \"none\": ignored by the hostless layout")
        if host_set.get("reveal") is not None:
            ref(host_set["reveal"], "host_set.reveal")

    music = plan.get("music")
    if music is not None and not isinstance(music, dict):
        err("`music` must be an object")
    elif music:
        number(music, "bpm", "music")
        number(music, "level_db", "music")
        if isinstance(music.get("bpm"), (int, float)) and not isinstance(music.get("bpm"), bool) and music["bpm"] <= 0:
            err(f"music: bpm {music['bpm']} must be > 0 (use sections \"none\" for silence)")
        secs = music.get("sections") or {}
        if not isinstance(secs, dict):
            err("music.sections must be an object {chapter key: section}")
            secs = {}
        for k, v in secs.items():
            if k not in key_set:
                err(f"music.sections: unknown chapter '{k}'")
            if v not in MUSIC_SECTIONS:
                err(f"music.sections.{k}: unknown section '{v}' (allowed: {', '.join(sorted(MUSIC_SECTIONS))})")

    # ---------- big sound effects budget ----------
    if fmt and sections and total_words:
        lo_s, hi_s = fmt["big_sfx_every_s"]
        if lo_s > 0 and hi_s > 0:
            most, least = est / lo_s, est / hi_s
            if big > most + 0.5 or big < least - 0.5:
                warn(f"{big} big sfx (gain >= {BIG_SFX_GAIN}) for about {est:.0f} s: format '{fid}' wants one every "
                     f"{lo_s}-{hi_s} s, i.e. {max(0, round(least))}-{round(most)}")

    # ---------- media ----------
    ep_root = ep_dir.resolve()
    for c in chapters:
        if not isinstance(c, dict) or not c.get("key"):
            continue
        k, media = c["key"], c.get("media")
        if c.get("scene") == "media" and not media:
            warn(f"chapter {k}: scene \"media\" without any `media` item yet")
        if media is None:
            continue
        if not isinstance(media, list):
            err(f"chapter {k}: `media` must be a list")
            continue
        if media and c.get("scene") != "media":
            warn(f"chapter {k}: `media` is set but the scene is '{c.get('scene')}', not \"media\": ignored")
        for i, item in enumerate(media):
            label = f"chapter {k} media[{i}]"
            if not isinstance(item, dict) or not isinstance(item.get("src"), str) or not item.get("src"):
                err(f"{label}: missing `src`")
                continue
            label += f" ({item['src']})"
            path = (ep_root / item["src"]).resolve()
            if ep_root not in path.parents:
                err(f"{label}: src must stay inside the episode folder")
            elif not path.is_file():
                err(f"{label}: file not found under {ep_dir}")
            ext = pathlib.PurePosixPath(item["src"]).suffix.lower()
            by_ext = next((kind for kind, exts in MEDIA_EXT.items() if ext in exts), None)
            kind = item.get("kind")
            if kind is not None and kind not in MEDIA_EXT:
                err(f"{label}: unknown kind '{kind}' (allowed: image, video)")
            elif by_ext is None:
                warn(f"{label}: extension '{ext}' is neither a known image nor a known video")
            elif kind is not None and kind != by_ext:
                err(f"{label}: kind '{kind}' but the extension '{ext}' is {by_ext}")
            elif kind is None and by_ext == "video":
                warn(f"{label}: video file without `kind: \"video\"`")
            enum(item, "fit", MEDIA_FIT, label)
            enum(item, "motion", MEDIA_MOTION, label)
            number(item, "start", label)
            if "word" in item:
                ref({"chapter": k, "word": item["word"]}, label)
            if not str(item.get("credit") or "").strip():
                warn(f"{label}: no `credit` (author / source / licence)")

    # ---------- opening (hook-first opening, docs/ENGINE_CONTRACT.md) ----------
    opening = plan.get("opening")
    first_blocks = blocks.get(keys[0]) or [] if keys and keys[0] else []
    if opening is None:
        if plan.get("layout") == 2:
            # docs/RETENTION.md rule 1: every new episode states its subject at frame 0
            (err if (fmt or {}).get("production", "code") == "code" else warn)(
                "no `opening`: frame 0 (also the cover) must state the subject, funny and with impact "
                "(docs/RETENTION.md; add \"opening\": {\"title\": \"... | ... *WORD*\"})")
    elif not isinstance(opening, dict) or not isinstance(opening.get("title"), str) or not opening["title"].strip():
        err("opening: must be an object with a `title` string")
    else:
        title = opening["title"]
        lines = [l.strip() for l in title.split("|") if l.strip()]
        if not 1 <= len(lines) <= 3:
            warn(f"opening.title has {len(lines)} lines (1-3 expected; the engine shows the first 3)")
        n_title = sum(len(l.replace("*", "").split()) for l in lines)
        if n_title > 9:
            warn(f"opening.title has {n_title} words: a hook sentence is at most 9 words (docs/RETENTION.md)")
        for l in lines:
            clean = l.replace("*", "")
            n = len([x for x in clean.split() if re.search(r"\w", x)])
            if n > 5:
                warn(f"opening.title: line '{clean}' has {n} words (max 5 to be read at a glance)")
            elif len(clean) > OPENING_LINE_CHARS:
                warn(f"opening.title: line '{clean}' has {len(clean)} characters: it will be set small "
                     f"(up to {OPENING_LINE_CHARS} for big type, a line is sized to fill the width)")
        if title.count("*") % 2:
            err("opening.title has an unclosed *accent*")
        else:
            accents = re.findall(r"\*([^*]+)\*", title)
            if len(accents) != 1:
                warn(f"opening.title has {len(accents)} *accent* words (exactly one expected)")
            elif len(accents[0].split()) > 1 or "|" in accents[0]:
                warn(f"opening.title: the accent '{accents[0]}' is more than one word")
        if opening.get("host", "bust") not in OPENING_HOST:
            err(f"opening: unknown host '{opening.get('host')}' (allowed: {', '.join(sorted(OPENING_HOST))})")
        elif "host" in opening and hostless:
            warn("opening.host is set but character is \"none\": ignored")
        until = opening.get("until")
        if until is not None and (not isinstance(until, str) or not until.strip()):
            err("opening.until must be a word of the first chapter")
        elif until is not None and keys and keys[0]:
            ref({"chapter": keys[0], "word": until}, "opening.until")
        # how long the opening lasts: up to the block of `until`, or to the end of the first sentence
        if first_blocks:
            w = until.lower() if isinstance(until, str) and until.strip() else None
            end = next((i for i, b in enumerate(first_blocks)
                        if (w in b.lower() if w else re.search(r"[.!?][\"»]?$", b.strip()))), len(first_blocks) - 1)
            secs = sum(spoken_words(b) for b in first_blocks[:end + 1]) / WORDS_PER_SECOND
            if secs > OPENING_MAX_S:
                warn(f"opening: about {secs:.1f} s of speech up to its last block; the engine cuts it at {OPENING_MAX_S} s "
                     "(the title leaves before the sentence ends)")
        # the hook comes first: a greeting in the first two blocks delays it
        if not hostless and (fmt is None or fmt.get("default_character", "none") != "none"):
            for b in first_blocks[:2]:
                if GREETING.search(b):
                    (err if plan.get("layout") == 2 else warn)(
                        f"the script starts with a greeting ('{b}'): nothing comes before the hook sentence "
                        "(docs/RETENTION.md); move the greeting after the promise or to the end")
                    break

    # ---------- follow call (docs/RETENTION.md rule 4): one near the first third, one in the last lines ----------
    if plan.get("layout") == 2 and plan.get("follow_call", True):
        flat = [b for k in keys if k in blocks for b in blocks[k]]
        total_w = sum(spoken_words(b) for b in flat) or 1
        seen, calls = 0, []
        for b in flat:
            if FOLLOW.search(b):
                calls.append(seen / total_w)
            seen += spoken_words(b)
        if not any(0.22 <= c <= 0.45 for c in calls):
            warn("no follow call near the first third of the script (a spoken line with 'abonne-toi' / 'follow', "
                 "between 28 % and 40 % of the words; docs/RETENTION.md rule 4)")
        if not any(c >= 0.85 for c in calls):
            warn("no follow call in the last lines (the end line: follow promise + one place to go; "
                 "docs/RETENTION.md rule 4)")

    # ---------- series ----------
    series = plan.get("series")
    if series is not None:
        if not isinstance(series, dict) or not isinstance(series.get("slug"), str) or not series.get("slug"):
            err("series: missing `slug`")
        else:
            slug, part, total = series["slug"], series.get("part"), series.get("total")
            if isinstance(part, bool) or not isinstance(part, int) or part < 1:
                err(f"series: `part` must be an integer >= 1 (got {part!r})")
            elif total is not None and (isinstance(total, bool) or not isinstance(total, int) or total < part):
                err(f"series: `total` {total!r} must be an integer >= part {part}")
            if not (ROOT / "series" / slug / "bible.md").is_file():
                err(f"series: series/{slug}/bible.md not found (the bible is written before the first episode)")

    return finish(ep_dir, [], f"{len(chapters)} chapters, {sum(len(b) for b in blocks.values())} blocks, "
                               f"{total_words} words (about {est:.0f} s), {big} big sfx, format {fid}")


def finish(ep_dir, fatal, summary=""):
    errors.extend(fatal)
    for w in warns:
        print("WARN ", w)
    for e in errors:
        print("ERROR", e)
    print(f"lint {ep_dir.name or ep_dir}: {len(errors)} error(s), {len(warns)} warning(s)" + (f" · {summary}" if summary else ""))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
